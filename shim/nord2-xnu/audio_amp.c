int nah_amp_cold_init(const struct na8_io *io,void *cookie,struct na8_state *bus,
 unsigned slave,uint16_t rev)
{
 const struct setting *table=0; unsigned count=0;
 if (slave!=0x34 && slave!=0x37) return -1;
 switch (rev) {
 case 0x0a73: table=ra73; count=sizeof(ra73)/sizeof(ra73[0]); break;
 case 0x0b73: table=rb73; count=sizeof(rb73)/sizeof(rb73[0]); break;
 case 0x1a73: break;
 case 0x0a74: table=ra74; count=sizeof(ra74)/sizeof(ra74[0]); break;
 case 0x0b74: table=rb74; count=sizeof(rb74)/sizeof(rb74[0]); break;
 case 0x0c74: table=rc74; count=sizeof(rc74)/sizeof(rc74[0]); break;
 default: return -1;
 }
 uint16_t system=0,key=0;
 if (na8_read16(io,cookie,bus,slave,0x00,&system) || (system&9)!=1) return -1;
 #define WRITE(r,v) do { if (na8_write16(io,cookie,bus,slave,(r),(v))) return -2; } while (0)
 WRITE(0x0f,0x5a6b);
 if (na8_read16(io,cookie,bus,slave,0xfb,&key)) return -2;
 WRITE(0xa0,key^0x005a);
 /* tfa98xx_key2(tfa,0), tfa_dsp.c:819-830; closes unhide window. */
 WRITE(0x0f,0x5a6b); WRITE(0xa1,0x005a); WRITE(0x0f,0);
 for (unsigned i=0;i<count;i++) WRITE(table[i].reg,table[i].value);
 if ((rev&255)==0x73) {
  uint16_t v=0;
  if (na8_read16(io,cookie,bus,slave,0x04,&v)) return -2;
  WRITE(0x04,v & ~(1u<<8)); /* FSSYNCEN0, tfa_init.c:852 */
 }
 /* Keep key2 unlocked until board profile analog settings are applied. */
 #undef WRITE
 return 0;
}
int nah_amp_lock(const struct na8_io *io,void *cookie,struct na8_state *bus,unsigned slave)
{
 if (na8_write16(io,cookie,bus,slave,0x0f,0x5a6b) ||
     na8_write16(io,cookie,bus,slave,0xa1,0) ||
     na8_write16(io,cookie,bus,slave,0x0f,0)) return -1;
 return 0;
}
