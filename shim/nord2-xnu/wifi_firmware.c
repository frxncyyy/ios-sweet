static void wipe(unsigned char *p, size_t n) { volatile unsigned char *v=p; while(n--) *v++=0; }
static int hash_ok(const unsigned char *p, size_t n, const unsigned char expected[32]) {
 unsigned char sum[32]; unsigned diff=0; SHA256_CTX ctx;
 SHA256_Init(&ctx); SHA256_Update(&ctx,p,n); SHA256_Final(sum,&ctx);
 for (unsigned i=0;i<32;i++) diff|=sum[i]^expected[i];
 wipe(sum,sizeof(sum)); return diff==0;
}
/* LZ4 block grammar, exact output, no unchecked speculative reads/copies.
 * Every iteration consumes input or output; all lengths bounded before add. */
int nwf_lz4(const unsigned char *s,size_t n,unsigned char *d,size_t cap) {
 size_t ip=0,op=0;
 if (!s || !d) return -1;
 while(ip<n) {
  unsigned token=s[ip++]; size_t lit=token>>4,match=(token&15)+4;
  if(lit==15) { unsigned x; do { if(ip==n) return -1; x=s[ip++]; if(x>cap || lit>cap-x) return -1; lit+=x; } while(x==255); }
  if(lit>n-ip || lit>cap-op) return -1;
  memcpy(d+op,s+ip,lit); ip+=lit; op+=lit;
  if(ip==n) return op==cap?0:-1;
  if(n-ip<2) return -1;
  size_t off=s[ip]|((size_t)s[ip+1]<<8); ip+=2;
  if(!off || off>op) return -1;
  if((token&15)==15) { unsigned x; do { if(ip==n) return -1; x=s[ip++]; if(x>cap || match>cap-x) return -1; match+=x; } while(x==255); }
  if(match>cap-op) return -1;
  for(size_t j=0;j<match;j++) { d[op]=d[op-off]; op++; }
 }
 return op==cap?0:-1;
}
int nwf_load(nwf_read_fn read,void *ctx,unsigned char *out,size_t outcap,
 unsigned char *scratch,size_t scratchcap,struct nwf_blob blobs[NWF_FILE_COUNT]) {
 size_t base=0; int rc=-1;
 if(!blobs) return -1;
 memset(blobs,0,sizeof(*blobs)*NWF_FILE_COUNT);
 if(!read || !out || !scratch || outcap<NWF_OUTPUT_BYTES || scratchcap<NWF_SCRATCH_BYTES) return -1;
 /* Distinct buffers required; reject overlap and pointer-end wrap. */
 uintptr_t a=(uintptr_t)out,b=(uintptr_t)scratch;
 if(a>UINTPTR_MAX-NWF_OUTPUT_BYTES || b>UINTPTR_MAX-NWF_SCRATCH_BYTES ||
    (a<b+NWF_SCRATCH_BYTES && b<a+NWF_OUTPUT_BYTES)) return -1;
 for(unsigned i=0;i<NWF_FILE_COUNT;i++) {
  const struct image *f=&images[i]; uint32_t logical=0;
  if(f->bytes>NWF_OUTPUT_BYTES-base || f->first>16 || f->count>16-f->first) goto fail;
  for(unsigned j=0;j<f->count;j++) {
   const struct extent *e=&extents[f->first+j];
   if(e->logical!=logical || e->bytes>f->bytes-logical || !e->stored ||
      e->stored>NWF_SCRATCH_BYTES || e->offset>NWF_VENDOR_BYTES ||
      e->stored>NWF_VENDOR_BYTES-e->offset || e->padding>=e->stored) goto fail;
   if(read(ctx,e->offset,scratch,e->stored) || !hash_ok(scratch,e->stored,e->hash)) goto fail;
   for(unsigned k=0;k<e->padding;k++) if(scratch[k]) goto fail;
   if(e->plain) { if(e->padding || e->bytes>e->stored) goto fail; memcpy(out+base+logical,scratch,e->bytes); }
   else if(nwf_lz4(scratch+e->padding,e->stored-e->padding,out+base+logical,e->bytes)) goto fail;
   logical+=e->bytes;
  }
  if(logical!=f->bytes || !hash_ok(out+base,f->bytes,f->hash)) goto fail;
  base+=f->bytes;
 }
 if(base!=NWF_OUTPUT_BYTES) goto fail;
 base=0;
 for(unsigned i=0;i<NWF_FILE_COUNT;i++) { blobs[i].name=images[i].name; blobs[i].data=out+base; blobs[i].size=images[i].bytes; base+=images[i].bytes; }
 rc=0;
fail:
 wipe(scratch,NWF_SCRATCH_BYTES);
 if(rc) wipe(out,NWF_OUTPUT_BYTES);
 return rc;
}
